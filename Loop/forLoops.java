package Loop;

public class forLoops {
    public static void main(String[] args) {
        // 1 to 10
        for(int i = 10; i >= 1; i--){  //boolen - true / false
            System.out.println(i);
        }
        /*
        Flow of control of for
        1. First assignment statement is excuted (variable defintion).
        2. Then second conditional statement is evaluted the body of the loop.
        3. Once loop body is finished, control flow will go back to the for statement, and
        third increment statement will be evaluted.
        5. Again, conditional statement is evaluted.
        6. Repeat 2-5.
        */
    }
}
